/* Builds nova-clips-data.js from the list of video file names in your Cloudflare Pages folder.
   Usage:  node tools/build-clips-data.js [list.txt] [base-url]
   list.txt = one file name per line (default tools/clips-list.txt).
   To refresh the list after adding videos, run inside the video folder:
     Windows PowerShell:  Get-ChildItem *.mp4 | % Name | Out-File -Encoding utf8 clips-list.txt
     Mac/Linux:           ls *.mp4 > clips-list.txt */
const fs = require('fs'), path = require('path');
const list = process.argv[2] || path.join(__dirname, 'clips-list.txt');
const BASE = (process.argv[3] || 'https://nova-reel-clips.pages.dev/cosmic_archadia/').replace(/\/?$/, '/');
const names = fs.readFileSync(list, 'utf8').split(/\r?\n/).map(s => s.trim()).filter(f => /\.mp4$/i.test(f));
const uniq = [...new Set(names)];
/* newest first: sort by the YYYY-MM-DD in the name, then by the long post id */
const key = f => ({ d: (f.match(/\d{4}-\d{2}-\d{2}/) || ['0000-00-00'])[0], id: (f.match(/_(\d{12,})\.mp4$/) || [0, '0'])[1] });
uniq.sort((a, b) => { const x = key(a), y = key(b); return y.d.localeCompare(x.d) || (y.id.length - x.id.length) || y.id.localeCompare(x.id); });
const out = `/* AUTO-GENERATED by tools/build-clips-data.js — ${uniq.length} Nova Clips. Do not edit by hand. */\nwindow.NOVA_CLIPS = ${JSON.stringify({ base: BASE, files: uniq })};\n`;
fs.writeFileSync(path.join(__dirname, '../nova-clips-data.js'), out);
console.log(uniq.length + ' clips -> nova-clips-data.js (base ' + BASE + ')');
